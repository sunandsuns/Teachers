    """静态校验感悟数据的完整性，返回错误列表（空列表表示通过）。"""
    errors: list[str] = []
    seen_texts: set[str] = set()
    for i, ins in enumerate(INSIGHTS):
        if not ins.text.strip():
            errors.append(f"[{i}] 原文为空")
        if ins.text in seen_texts:
            errors.append(f"[{i}] 原文重复: {ins.text[:20]}")
        seen_texts.add(ins.text)
        if not ins.interpretation.strip():
            errors.append(f"[{i}] 解读为空: {ins.text[:20]}")
        if not ins.source.strip():
            errors.append(f"[{i}] 出处为空: {ins.text[:20]}")
        if not ins.book_id.strip():
            errors.append(f"[{i}] book_id 为空: {ins.text[:20]}")
        if not ins.themes:
            errors.append(f"[{i}] 缺少主题标签: {ins.text[:20]}")
        for t in ins.themes:
            if t not in VALID_THEMES:
                errors.append(f"[{i}] 未知主题 '{t}': {ins.text[:20]}")
    return errors
