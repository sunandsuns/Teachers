/**
 * 前端自己的类型。
 *
 * 接口形状**不在这里**——那些在 `./types.gen`，由后端 OpenAPI 生成
 * （`npm run gen:api`）。这个文件只留后端表达不了的概念。
 *
 * 为什么还留这一层：前端各处都从 `./types` / `../api/client` 取类型，让生成物
 * 走同一个路径，等于换掉实现而不用动任何调用方。
 *
 * 以前这个文件是 585 行手抄的。手抄的代价不是"多打一遍字"，而是它会和契约
 * 分头演化且无人察觉：实测其中 49 个类型是后端 schema 的逐字段副本（零差异），
 * 只是 26 个名字不一样——同一个形状说了两遍，两边从此可以各自漂移。
 */

export * from './types.gen'

/**
 * 检索范围。
 *
 * `all` 是**前端概念**：它表示"不带 kind 过滤"，后端没有这个值，所以不在生成物
 * 里。生成物里的 `SearchResultKind` 才是后端真的会返回的三种。
 */
export type SearchKind = 'all' | 'notes' | 'source' | 'shelf'
